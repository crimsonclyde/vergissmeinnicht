import { afterEach, expect, it, vi } from 'vitest';
import { randomUUID } from 'node:crypto';
import { startTestApp } from './test-harness.ts';
let app: Awaited<ReturnType<typeof startTestApp>> | undefined;
afterEach(async () => app?.close());
const payload = { query: 'Via Roma 2, Soldano', consent: true };
const response = () => new Response(JSON.stringify({ type: 'FeatureCollection', features: [{ type: 'Feature', properties: { name: 'Pub', osm_type: 'N', osm_id: 1 }, geometry: { type: 'Point', coordinates: [7.7, 43.9] } }] }));
it('requires consent, CSRF, editor authority and an enabled Workspace; lookup never saves a place', async () => {
  const fetcher = vi.fn<typeof fetch>().mockImplementation(async () => response());
  app = await startTestApp({ mapAddressFetch: fetcher, captureLogs: true });
  const workspace = await app.createWorkspace('Map'); const foreign = await app.createWorkspace('Other');
  const base = '/api/workspaces/' + workspace + '/map';
  const current = app;
  const tool = (enabled: boolean) => current.post('/api/workspaces/' + workspace + '/tools', { tool: 'MAP', enabled }, current.admin);
  const guest = await app.invite('address-guest@example.org', 'Guest');
  const user = await app.invite('address-user@example.org', 'User');
  const editor = await app.invite('address-editor@example.org', 'Editor');
  for (const [email, role] of [['address-guest@example.org', 'GUEST'], ['address-user@example.org', 'USER'], ['address-editor@example.org', 'EDITOR']] as const) await app.addMember(workspace, email, role);
  expect((await app.post(base + '/address-search', payload, app.admin)).statusCode).toBe(404);
  await tool(true);
  for (const cookie of [guest, user]) expect((await app.post(base + '/address-search', payload, cookie)).statusCode).toBe(403);
  expect((await app.post('/api/workspaces/' + foreign + '/map/address-search', payload, editor)).statusCode).toBe(404);
  for (const bad of [{ query: payload.query }, { ...payload, consent: false }, { ...payload, url: 'http://localhost' }]) expect((await app.post(base + '/address-search', bad, editor)).statusCode).toBe(400);
  expect((await app.app.inject({ method: 'POST', url: base + '/address-search', payload, headers: { cookie: editor } })).statusCode).toBe(403);
  expect(fetcher).not.toHaveBeenCalled();
  const result = await app.post(base + '/address-search', payload, editor);
  expect(result.statusCode, result.body).toBe(200);
  expect(result.json().candidates).toHaveLength(1);
  expect((await app.get(base + '/places', app.admin)).json().places).toEqual([]);
  const point = result.json().candidates[0];
  expect((await app.post(base + '/places', { operationId: randomUUID(), place: { name: 'Reviewed pub', points: [{ role: 'destination', preferred: true, newPoint: { label: 'Reviewed pub', latitude: point.latitude, longitude: point.longitude, precision: 'approximate', provenance: point.sourceUrl } }] } }, editor)).statusCode).toBe(200);
  expect((await app.post(base + '/address-search', payload, app.admin)).statusCode).toBe(200);
  expect(fetcher).toHaveBeenCalledTimes(1);
  expect(app.logs).not.toContain(payload.query);
});
it('withholds results when the tool is disabled while a lookup is in flight', async () => {
  let release!: () => void; let started!: () => void;
  const waiting = new Promise<void>(resolve => { release = resolve; });
  const called = new Promise<void>(resolve => { started = resolve; });
  app = await startTestApp({ mapAddressFetch: async () => { started(); await waiting; return response(); } });
  const workspace = await app.createWorkspace('Map'); const path = '/api/workspaces/' + workspace;
  await app.post(path + '/tools', { tool: 'MAP', enabled: true }, app.admin);
  const request = app.post(path + '/map/address-search', payload, app.admin);
  await called;
  await app.post(path + '/tools', { tool: 'MAP', enabled: false }, app.admin);
  release();
  expect((await request).statusCode).toBe(404);
});
it('persists the per-account budget without storing the address', async () => {
  app = await startTestApp({ mapAddressFetch: async () => response() });
  const workspace = await app.createWorkspace('Map'); const path = '/api/workspaces/' + workspace;
  await app.post(path + '/tools', { tool: 'MAP', enabled: true }, app.admin);
  for (let i = 0; i < 20; i++) expect((await app.post(path + '/map/address-search', payload, app.admin)).statusCode).toBe(200);
  expect((await app.post(path + '/map/address-search', payload, app.admin)).statusCode).toBe(429);
  await app.restart();
  expect((await app.post(path + '/map/address-search', payload, app.admin)).statusCode).toBe(429);
  expect(JSON.stringify(app.database.sqlite.prepare('SELECT * FROM rate_limits').all())).not.toContain('Soldano');
});
it.each(['role', 'membership', 'account'])('withholds results after %s revocation during lookup', async change => {
  const current = await startTestApp({ mapAddressFetch: async () => {
    if (change === 'role') current.database.sqlite.prepare("UPDATE memberships SET role='GUEST' WHERE workspace_id=?").run(workspace);
    else if (change === 'membership') current.database.sqlite.prepare('DELETE FROM memberships WHERE workspace_id=?').run(workspace);
    else current.database.sqlite.prepare("UPDATE users SET status='DISABLED'").run();
    return response();
  } });
  app = current; const workspace = await app.createWorkspace('Map'); const path = '/api/workspaces/' + workspace;
  await app.post(path + '/tools', { tool: 'MAP', enabled: true }, app.admin);
  expect([403, 404]).toContain((await app.post(path + '/map/address-search', payload, app.admin)).statusCode);
});
